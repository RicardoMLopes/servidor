SELECT APLICACAO,CODIGO, CODIGOBARRA, DESCRICAO, 
	UNIDADE AS EMBALAGEM, PRECOVENDA AS PREC_VTA_UNIT, 
	PRECOVENDA*UNIDADE AS PREC_VTA_EMB, 
	PRECOVENDA*1.03  AS PREC_PZO_UNIT, 
	PRECOVENDA*UNIDADE*1.03 AS PREC_PZO_EMB  
FROM CADPRODUTO
WHERE SaldoEstoque > 3
OR (precocusto >= '6.00' AND SALDOESTOQUE >= 1)
and situacaoregistro<> 'E'
ORDER BY aplicacao,descricao

